// Unified post-fill settlement — fee (user-user only, actual-fill-based),
// realized spread capture (house-attributed fills only), and per-market
// average-cost tracking, computed together from the same actual-fill data in
// one pass (plan §5). Counterparty attribution reuses matching.mjs's
// walkBook — no duplicated book-walking logic between market orders and fees.
import { QueryCommand } from '@aws-sdk/lib-dynamodb';
import { walkBook } from './matching.mjs';

export const FEE_RATE = 0.07;

// Polymarket-style: fee = shares * p(1-p) * rate, taker side only, never
// charged on house liquidity fills (house earns via spread instead).
export function computeFee(shares, execPriceCents) {
  const p = execPriceCents / 100;
  return shares * p * (1 - p) * FEE_RATE;
}

const WALLET_STUB = process.env.WALLET_STUB || 'http://localhost:3000';

// Poll bb_pending_bids for the actual fill(s) generated by `submittedBidId` —
// the matcher writes per-price-level CHILD records (parentBidId ===
// submittedBidId) rather than mutating the original bid's buyingPrice, so we
// collect those (falling back to the original record itself for an exact
// single-price full fill). Returns [] on timeout — callers must treat that as
// "skip accounting for this fill", never as "zero fill" (plan §5 step 1:
// correctness over eagerness).
async function pollActualFills(ddb, marketId, userId, submittedBidId) {
  const mk = `${marketId}.${userId}`;
  for (let attempt = 0; attempt < 3; attempt++) {
    if (attempt > 0) await new Promise((r) => setTimeout(r, 300));
    // Query the exact partition (marketId.userId) — the matcher writes child
    // fill records (parentBidId === submittedBidId) under the SAME partition
    // as the original bid, so this finds everything without a table-wide scan
    // (bb_pending_bids grows unbounded across all users/markets — a Scan here
    // silently misses records past whatever page DynamoDB returns first).
    const q = await ddb.send(new QueryCommand({
      TableName: 'bb_pending_bids',
      KeyConditionExpression: 'marketId = :mk',
      ExpressionAttributeValues: { ':mk': mk },
      ConsistentRead: true,
    }));
    const items = (q.Items || []).filter((x) => x.bidId === submittedBidId || x.parentBidId === submittedBidId);
    const fills = items.filter((x) => Number(x.matchedBidsCount) > 0);
    if (fills.length) return fills.map((f) => ({ qty: Number(f.matchedBidsCount), priceCents: Number(f.bidAmount) }));
  }
  return [];
}

// preTradeBook: the opposite-side resting rows (with rowId) captured BEFORE
// the trade was submitted — used only for counterparty attribution (which
// resting rows this fill actually walked through), not for the fill
// quantity/price itself (that comes from pollActualFills, the real source of
// truth). fairValueAtFillFn(): () => number, YES probability [0,1] at fill time.
export async function settleFill({ marketId, userId, side, submittedBidId, preTradeBook, fairValueYesAtFill, db, ddb, redis, MMP_USER_ID }) {
  const fills = await pollActualFills(ddb, marketId, userId, submittedBidId);
  if (!fills.length) return { skipped: true };

  const totalQty = fills.reduce((s, f) => s + f.qty, 0);
  const { consumed } = walkBook(preTradeBook, totalQty);

  let houseShares = 0, userShares = 0, houseNotional = 0;
  for (const row of consumed) {
    if (row.userId === MMP_USER_ID) { houseShares += row.takenQty; houseNotional += row.takenQty * row.price; }
    else userShares += row.takenQty;
  }

  // avg execution price (¢) actually paid/received, weighted across fill slices
  const notional = fills.reduce((s, f) => s + f.qty * f.priceCents, 0);
  const avgExecPriceCents = totalQty > 0 ? notional / totalQty : 0;

  let fee = 0;
  if (userShares > 0) {
    fee = computeFee(userShares, avgExecPriceCents);
    if (fee > 0) {
      await fetch(`${WALLET_STUB}/wallet/debit`, {
        method: 'POST', headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ user_id: userId, amount: fee }),
      }).catch(() => {});
      await redis.incrbyfloat('app:mm:feeRevenue', fee.toFixed(4));
    }
    await redis.hincrby('app:mm:volume', 'userUserVolume', userShares);
  }

  let realizedSpreadContribution = 0;
  let houseAvgExecCents = null;
  if (houseShares > 0) {
    const fairYesAtFill = fairValueYesAtFill();
    houseAvgExecCents = houseNotional / houseShares;
    if (side === 'YES') {
      // taker bought YES from the house's resting NO bid -> house is the NO
      // buyer (functionally sold YES) at (100 - houseAvgExecCents)
      const execYesEquivalent = 100 - houseAvgExecCents;
      realizedSpreadContribution = (execYesEquivalent - fairYesAtFill * 100) * houseShares / 100;
    } else {
      // taker bought NO from the house's resting YES bid -> house bought YES
      realizedSpreadContribution = (fairYesAtFill * 100 - houseAvgExecCents) * houseShares / 100;
    }
    await redis.incrbyfloat('app:mm:realizedSpreadRevenue', realizedSpreadContribution.toFixed(4));
    await redis.hincrby('app:mm:volume', 'houseUserVolume', houseShares);
    await redis.incr('app:mm:fillcount'); // calibration: quoteFillRate numerator (§7)

    // Average-cost update — executed matched trades only, per-market keyed
    // (plan §5 step 6 / §7's inventoryPnL<->settlementPnL handoff).
    const costKey = `app:mm:invCost:${marketId}`;
    if (side === 'YES') { // house leg is NO
      await redis.hincrby(costKey, 'noQty', houseShares);
      await redis.hincrbyfloat(costKey, 'noCostSum', houseShares * houseAvgExecCents);
    } else { // house leg is YES
      await redis.hincrby(costKey, 'yesQty', houseShares);
      await redis.hincrbyfloat(costKey, 'yesCostSum', houseShares * houseAvgExecCents);
    }
  }

  return { skipped: false, totalQty, houseShares, userShares, fee, realizedSpreadContribution, avgExecPriceCents, houseAvgExecCents };
}
